"""Exercise the actual streaming C reader against generated ZIP fixtures."""
import ctypes
import pathlib
import subprocess
import tempfile
import zipfile

root = pathlib.Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory() as directory:
    out = pathlib.Path(directory) / "db.so"
    subprocess.run(["cc", "-std=c99", "-Wall", "-Wextra", "-Werror", "-shared", "-fPIC", "-Iinclude",
                    "src/maizo_cheatdb.c", "-lz", "-o", str(out)], cwd=root, check=True)
    lib = ctypes.CDLL(str(out))
    reader = ctypes.CFUNCTYPE(ctypes.c_int, ctypes.c_void_p, ctypes.c_uint32, ctypes.c_void_p, ctypes.c_size_t)
    lib.maizoCheatZipFind.argtypes = [reader, ctypes.c_void_p, ctypes.c_uint32, ctypes.c_char_p, ctypes.c_char_p,
                                      ctypes.POINTER(ctypes.c_void_p), ctypes.c_void_p]
    lib.maizoCheatZipFind.restype = ctypes.c_int
    libc = ctypes.CDLL(None)
    libc.free.argtypes = [ctypes.c_void_p]

    def find(data, serial=b"SLUS_123.45", title=b"Game One"):
        @reader
        def read(ctx, offset, dst, length):
            if offset + length > len(data):
                return 0
            ctypes.memmove(dst, data[offset:offset+length], length)
            return 1
        pointer = ctypes.c_void_p()
        heading = ctypes.create_string_buffer(256)
        result = lib.maizoCheatZipFind(read, None, len(data), serial, title, ctypes.byref(pointer), heading)
        text = ctypes.string_at(pointer) if pointer else b""
        libc.free(pointer)
        return result, text, heading.value

    def archive(members, method=zipfile.ZIP_DEFLATED):
        p = pathlib.Path(directory) / "fixture.zip"
        with zipfile.ZipFile(p, "w", compression=method) as z:
            for name, content in members:
                z.writestr(name, content)
        return p.read_bytes()

    valid = "Master Code\n90000000 12345678\nMoney\n20123456 00000001"
    aggregate = '"Game One (PAL)"\nWrong Region\n20000000 00000002\n"Game One (USA)"\r\n' + valid + '\n"Other Game"\nWrong\n20000000 FFFFFFFF'
    for method in (zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED):
        blob = archive([("CheatDatabase.txt", aggregate)], method)
        result, text, heading = find(blob)
        assert result == 1 and b"Money" in text and b"Wrong" not in text, (result, text, heading)
        assert find(blob, b"SLES_123.45")[1].startswith(b"Wrong Region")
        assert find(blob, b"SLUS_999.99", b"Missing")[0] == 0
        assert find(blob[:-5])[0] < 0
        assert find(b"not a zip" * 20)[0] < 0
        assert find(archive([]))[0] == 0
        result, text, _ = find(archive([("CheatDatabase.txt", aggregate), ("CHT/SLUS_123.45.cht", valid)], method))
        assert result == 2 and b"Money" in text
        assert find(archive([("one.txt", aggregate), ("two.txt", '"Game One (USA)"\nAnother\n20123456 12345678')]))[0] == -2
        assert find(archive([("SLUS_999.99.cht", valid)]))[0] == 0
        # Deflate spans chunks and EOF can be missing a newline.
        result, text, _ = find(archive([("huge.txt", '"Other"\n' + 'x' * 8000 + '\n' + aggregate)]))
        assert result == 1 and b"Money" in text
    # A large aggregate crosses thousands of 8 KiB inflate boundaries.
    import random
    rng = random.Random(43)
    prefix = b'"Other Game"\n' + b"".join(bytes(rng.randrange(32, 127) for _ in range(127)) + b"\n" for _ in range(2048))
    assert find(archive([("CheatDatabase.txt", prefix + b'\n"Game One (USA)"\n' + valid.encode())]))[0] == 1
    assert find(archive([("SLUS_123.45.cht", valid)], zipfile.ZIP_BZIP2))[0] == -5
    blob = archive([("SLUS_123.45.cht", valid)], zipfile.ZIP_STORED)
    damaged = bytearray(blob)
    damaged[30 + len("SLUS_123.45.cht")] ^= 1
    assert find(bytes(damaged))[0] == -6
    assert find(blob, b"invalid")[0] == -8
    assert find(archive([("SLUS_123.45.cht", "x" * (260 * 1024))]))[0] == -4
    # Local ZIP64 extra fields, with normal-sized central directory,
    # as generated by some archivers for streaming members.
    p = pathlib.Path(directory) / "local64.zip"
    with zipfile.ZipFile(p, "w", compression=zipfile.ZIP_DEFLATED) as z:
        with z.open("SLUS_123.45.cht", "w", force_zip64=True) as f:
            f.write(valid.encode())
    assert find(p.read_bytes())[0] == 2
    assert find(archive([("empty.txt", ""), ("CheatDatabase.txt", aggregate)]))[0] == 1
    assert find(archive([("CheatDatabase.txt", aggregate)]),title=b"Game One (USA)")[0] == 1
    print("CheatDevice ZIP tests passed")
    import os, re, io, collections
    original=os.environ.get("MAIZO_OFFICIAL_CHEAT_ZIP")
    if original:
        with zipfile.ZipFile(original) as release:
            names=[n for n in release.namelist() if n.rsplit("/",1)[-1].lower()=="cheatdatabase.zip"]
            assert len(names)==1, release.namelist()
            original_zip=release.read(names[0])
        sections=[]
        with zipfile.ZipFile(io.BytesIO(original_zip)) as z:
            for n in z.namelist():
                if n.lower().endswith(".txt"):
                    sections.extend(l.strip()[1:-1] for l in z.read(n).splitlines()
                                    if l.strip().startswith(b'"') and l.strip().endswith(b'"') and len(l.strip())>2)
        assert len(sections)>100
        counts=collections.Counter(sections)
        tested=0
        for heading in sections:
            if counts[heading]!=1 or len(heading)>=200: continue
            match=re.search(rb"\((USA|US|NTSC-U|PAL|Europe|Japan|NTSC-J)\)$",heading,re.I)
            if not match or re.search(rb"S[A-Z]{3}[-_ ]?\d{3}[.]?\d{2}",heading,re.I): continue
            region=match.group(1).lower()
            serial=b"SLES_999.99" if region in (b"pal",b"europe") else b"SLPS_999.99" if region in (b"japan",b"ntsc-j") else b"SLUS_999.99"
            result, text, actual=find(original_zip,serial,heading)
            if result==1 and actual==heading and text: tested+=1
            if tested==5: break
        assert tested==5, ("official release compatible headings",tested)
        assert find(original_zip,b"SLUS_999.99",b"MAIZO_NOT_A_REAL_GAME")[0]==0
        print("Original CheatDevicePS2 release ZIP: five matched games + missing title PASS")
